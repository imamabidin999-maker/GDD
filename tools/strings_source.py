        writer = csv.writer(f, quoting=csv.QUOTE_MINIMAL)
        writer.writerow(["keys", "id", "en"])
        for key, text_id, text_en in STRINGS:
            if key in keys:
                raise SystemExit(f"Kunci ganda: {key}")
            keys.add(key)
